def main():
    seed = json.loads(SEED.read_text(encoding="utf-8"))
    questions = {q["questionId"]: q for q in seed["questions"]}

    applied = 0
    for qid, rewrites in REWRITES.items():
        question = questions.get(qid)
        if question is None:
            print(f"警告: {qid} が見つかりません", file=sys.stderr)
            continue
        for label, text in rewrites.items():
            if label == question["correctChoice"]:
                print(f"警告: {qid} の正解 {label} は書き換えない", file=sys.stderr)
                continue
            question["choices"][label] = text
            applied += 1

    SEED.write_text(
        json.dumps(seed, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"{applied}件の誤答を書き換えました")
    return 0


if __name__ == "__main__":
    sys.exit(main())
